const fs = require("node:fs");
const path = require("node:path");

const { build } = require("esbuild");

const repositoryPath = path.resolve(__dirname, "..");
const outputPath = path.join(repositoryPath, "lib", "service-hub.mjs");

async function generateModule() {
  const result = await build({
    absWorkingDir: repositoryPath,
    entryPoints: ["src/service-hub.mjs"],
    outfile: "lib/service-hub.mjs",
    bundle: true,
    write: false,
    platform: "browser",
    format: "esm",
    target: ["es2022"],
    external: ["@lumine-code/event-kit"],
    define: {
      process: "{}",
    },
    charset: "utf8",
    legalComments: "none",
    sourcemap: false,
    banner: {
      js: "// Generated by `npm run build` from src/service-hub.mjs. Do not edit.",
    },
  });

  if (result.outputFiles.length !== 1) {
    throw new Error(
      `Expected one generated module, received ${result.outputFiles.length}`,
    );
  }
  return result.outputFiles[0].text;
}

async function main() {
  const generated = await generateModule();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outputPath)
      ? fs.readFileSync(outputPath, "utf8")
      : null;
    if (current !== generated) {
      throw new Error("lib/service-hub.mjs is stale; run `npm run build`");
    }
    return;
  }

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, generated);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
